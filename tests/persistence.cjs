// Real Chromium DOM, isolated browser partition. Does not read the user's workspace.
const {app,BrowserWindow}=require('electron');
const assert=require('node:assert/strict');
const {startWorkspaceServer}=require('./support/workspace-server.cjs');
app.whenReady().then(async()=>{
 const win=new BrowserWindow({show:false,webPreferences:{partition:'persistence-regression'}});
 let workspace;
 try{
  workspace=await startWorkspaceServer();
  await win.loadURL(workspace.origin+'/?isolated=1');
  const result=await win.webContents.executeJavaScript(`(async()=>{
   const tick=()=>new Promise(resolve=>setTimeout(resolve,20));
   const assert=(condition,message)=>{if(!condition)throw Error(message)};
   const uiErrors=[];window.addEventListener('error',e=>uiErrors.push(e.message));
   const paper={id:'regression-paper',title:'Regression paper',authors:'Test'};
   state.boards=[{id:'research',name:'Research',columns:['Queue','In progress']}];
   state.tasks=[{id:'test-task',text:'Drag me',board:'research',col:'Queue',tag:'test'}];
   state.papers=[paper];
   openEditor();const first=activeNoteId;
   insertPaperEmbed(paper);
   document.querySelector('[data-view="inbox"]').click();
   assert(state.notes.find(n=>n.id===first).content.includes('regression-paper'),'immediate navigation lost embed');
   openEditor(state.notes.find(n=>n.id===first));
   assert(document.querySelector('[data-paper-embed="regression-paper"]'),'reopening lost embed');
   document.querySelector('#saveNote').click();
   assert(currentDraftNote().versions.length===1,'manual version missing');
   document.querySelector('.editor .title').value='Changed title';
   document.querySelector('.editor .title').dispatchEvent(new Event('input'));
   document.querySelector('.editor-body').insertAdjacentHTML('beforeend','<table class="research-table"><tr><td>Saved cell</td></tr></table>');
   await tick();
   document.querySelector('#cancelEdit').click();
   openEditor(state.notes.find(n=>n.id===first));
   assert(document.querySelector('td')?.textContent==='Saved cell','table mutation lost');
   const oldConfirm=window.confirm;window.confirm=()=>true;rollbackDraft();window.confirm=oldConfirm;
   assert(document.querySelector('[data-paper-embed]'),'rollback lost embed');
   assert(!document.querySelector('td'),'rollback did not restore version');
   openEditor();const second=activeNoteId;insertPaperEmbed({...paper,id:'second-paper'});
   document.querySelector('#cancelEdit').click();
   assert(first!==second,'duplicate title reused note ID');
   openEditor(state.notes.find(n=>n.id===first));
   assert(!document.querySelector('[data-paper-embed="second-paper"]'),'duplicate title mixed notes');
   const persisted=JSON.parse(localStorage.getItem(STORAGE_KEY));
   assert(persisted.notes.find(n=>n.id===first).content.includes('regression-paper'),'storage lacks first paper');
   assert(persisted.notes.find(n=>n.id===second).content.includes('second-paper'),'storage lacks second paper');
   openEditor();const third=activeNoteId;
   openPaperComposer();
   document.querySelector('[data-unified-pick="regression-paper"]').click();
   document.querySelector('[data-view="board"]').click();
   openEditor(state.notes.find(n=>n.id===third));
   assert(document.querySelector('[data-paper-embed="regression-paper"]'),'real picker flow lost paper');
   insertEditorHTML('<figure><img src="data:image/png;base64,AA==" alt="Test image"></figure><p>Inserted block</p>');
   document.querySelector('#saveNote').click();
   document.querySelector('#cancelEdit').click();
   openEditor(state.notes.find(n=>n.id===third));
   assert(document.querySelector('figure img'),'manual save lost inserted block');
   const nativeSet=Storage.prototype.setItem;
   Storage.prototype.setItem=function(){throw new DOMException('Quota exceeded','QuotaExceededError')};
   document.querySelector('.editor .title').value='Must remain unsaved';
   assert(persistDraft()===false,'storage failure reported success');
   assert(document.querySelector('#saveStatus').textContent.includes('Save failed'),'storage failure invisible');
   Storage.prototype.setItem=nativeSet;
   assert(persistDraft()===true,'failed save could not be retried');
   document.querySelector('#cancelEdit').click();
   for(const view of ['search','skills','papers','board','inbox']){
    document.querySelector('[data-view="'+view+'"]').click();await tick();
   }
   state.folders.push({id:'parent',name:'Parent',icon:'folder'},{id:'child',name:'Child',icon:'folder',parentId:'parent'});
   assert(moveFolder('parent','child')===false,'folder cycle allowed');
   assert(moveFolder('child',null)===true,'moving folder to root failed');
   currentView='board';render();
   const card=document.querySelector('.task'),taskId=card.dataset.task;
   assert(card.getAttribute('role')==='button','task not accessible');
   assert(getComputedStyle(card).cursor==='grab','task lacks grab cursor');
   card.click();assert(document.querySelector('#hubTaskTitle'),'task click did not open editor');
   closeComposer();
   card.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
   assert(document.querySelector('#hubTaskTitle'),'keyboard edit failed');
   closeComposer();
   const transfer=new DataTransfer();
   card.dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:transfer}));
   assert(document.body.classList.contains('dragging-task'),'dragging cursor absent');
   const destination=document.querySelectorAll('.kanban-col')[1];
   destination.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:transfer}));
   assert(destination.classList.contains('drag-over'),'drop target feedback absent');
   destination.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer}));
   await tick();
   assert(!document.body.classList.contains('dragging-task'),'drag cursor stuck');
   assert(state.tasks.find(t=>t.id===taskId).col===destination.dataset.col,'task did not move');
   document.querySelector('.task[data-task="'+taskId+'"]').click();
   assert(!document.querySelector('#hubTaskTitle'),'drop accidentally opened editor');
   state.boards=[];currentView='board';render();
   assert(document.querySelector('#emptyBoard'),'empty board screen broken');
   assert(uiErrors.length===0,'UI errors: '+uiErrors.join('; '));
   return {first,second,key:STORAGE_KEY};
  })()`);
  await win.webContents.reload();
  await new Promise(resolve=>win.webContents.once('did-finish-load',resolve));
  const restored=await win.webContents.executeJavaScript(`(()=>{
    const note=state.notes.find(n=>n.id===${JSON.stringify(result.first)});
    openEditor(note);return Boolean(document.querySelector('[data-paper-embed="regression-paper"]'));
  })()`);
  assert.equal(restored,true,'reload lost paper');
  console.log('PASS: immediate navigation, reopen, manual versions, DOM edits, rollback, duplicate titles, real paper picker, inserted images, storage failure + retry, reload');
 }catch(error){console.error(error);process.exitCode=1}
 finally{win.destroy();await workspace?.close();app.exit(process.exitCode||0)}
});
